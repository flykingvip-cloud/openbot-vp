let cachedMethodScopeGroups: Record<OperatorScope, readonly string[]> | undefined;
let cachedMethodScopeByName: Map<string, OperatorScope> | undefined;

export function getMethodScopeGroups(): Record<OperatorScope, readonly string[]> {
  if (!cachedMethodScopeGroups) {
    cachedMethodScopeGroups = mergePackMethodsIntoScopeGroups(
      BASE_METHOD_SCOPE_GROUPS,
      GATEWAY_METHOD_PACK_MANIFEST as readonly GatewayMethodPack[],
    );
  }
  return cachedMethodScopeGroups;
}

function methodScopeByName(): Map<string, OperatorScope> {
  if (!cachedMethodScopeByName) {
    cachedMethodScopeByName = new Map<string, OperatorScope>(
      Object.entries(getMethodScopeGroups()).flatMap(([scope, methods]) =>
        methods.map((method) => [method, scope as OperatorScope]),
      ),
    );
  }
  return cachedMethodScopeByName;
}

const ADMIN_METHOD_PREFIXES = ["exec.approvals.", "config.", "wizard.", "update."] as const;

function resolveScopedMethod(method: string): OperatorScope | undefined {
  const explicitScope = methodScopeByName().get(method);
  if (explicitScope) {
    return explicitScope;
  }
  if (ADMIN_METHOD_PREFIXES.some((prefix) => method.startsWith(prefix))) {
    return ADMIN_SCOPE;
  }
  return undefined;
}

export function isApprovalMethod(method: string): boolean {
  return resolveScopedMethod(method) === APPROVALS_SCOPE;
}

export function isPairingMethod(method: string): boolean {
  return resolveScopedMethod(method) === PAIRING_SCOPE;
}

export function isReadMethod(method: string): boolean {
  return resolveScopedMethod(method) === READ_SCOPE;
}

export function isWriteMethod(method: string): boolean {
  return resolveScopedMethod(method) === WRITE_SCOPE;
}

export function isNodeRoleMethod(method: string): boolean {
  return NODE_ROLE_METHODS.has(method);
}

export function isAdminOnlyMethod(method: string): boolean {
  return resolveScopedMethod(method) === ADMIN_SCOPE;
}

export function resolveRequiredOperatorScopeForMethod(method: string): OperatorScope | undefined {
  return resolveScopedMethod(method);
}

export function resolveLeastPrivilegeOperatorScopesForMethod(method: string): OperatorScope[] {
  const requiredScope = resolveRequiredOperatorScopeForMethod(method);
  if (requiredScope) {
    return [requiredScope];
  }
  // Default-deny for unclassified methods.
  return [];
}

/**
 * `operator.admin` substitutes for other operator scopes, except methods that
 * require `operator.approvals` and must not accept admin as a stand-in.
 */
const ADMIN_SCOPE_DOES_NOT_SUBSTITUTE = new Set<string>([
  "platform.diagnosis.approval.decide",
  "enterprise.mesh.asset.pause",
  // Subject match is the grant. Admin must not open this method.
  "task.outcome.rejectResult",
]);

export function adminScopeSubstitutesForMethod(method: string): boolean {
  return !ADMIN_SCOPE_DOES_NOT_SUBSTITUTE.has(method);
}

export function authorizeOperatorScopesForMethod(
  method: string,
  scopes: readonly string[],
): { allowed: true } | { allowed: false; missingScope: OperatorScope } {
  // No operator scope grants this call. The gateway asks for platformUserId,
  // then the handler checks subjectRef and enterprise tenant.
  if (method === "task.outcome.rejectResult") {
    return { allowed: false, missingScope: APPROVALS_SCOPE };
  }
  if (scopes.includes(ADMIN_SCOPE) && adminScopeSubstitutesForMethod(method)) {
    return { allowed: true };
  }
  const requiredScope = resolveRequiredOperatorScopeForMethod(method) ?? ADMIN_SCOPE;
  if (requiredScope === PLATFORM_SCOPE) {
    if (scopes.includes(PLATFORM_SCOPE)) {
      return { allowed: true };
    }
    return { allowed: false, missingScope: PLATFORM_SCOPE };
  }
  if (requiredScope === READ_SCOPE) {
    if (scopes.includes(READ_SCOPE) || scopes.includes(WRITE_SCOPE)) {
      return { allowed: true };
    }
    return { allowed: false, missingScope: READ_SCOPE };
  }
  if (scopes.includes(requiredScope)) {
    return { allowed: true };
  }
  return { allowed: false, missingScope: requiredScope };
}

export function isGatewayMethodClassified(method: string): boolean {
  if (isNodeRoleMethod(method)) {
    return true;
  }
  return resolveRequiredOperatorScopeForMethod(method) !== undefined;
}

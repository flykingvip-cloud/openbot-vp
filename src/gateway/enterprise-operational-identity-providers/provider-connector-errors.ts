/**
 * Operational Identity 统一错误码（规范 v1.0 IDENTITY_XXX）。
 * 与现有 ENTERPRISE_IDENTITY_* 并存；新代码优先映射到 IDENTITY_XXX。
 */
export const OPERATIONAL_IDENTITY_ERROR = {
  CREDENTIAL_MISSING: "IDENTITY_001",
  AUTH_FAILED: "IDENTITY_002",
  TOKEN_EXPIRED: "IDENTITY_003",
  PERMISSION_DENIED: "IDENTITY_004",
  PROVIDER_UNAVAILABLE: "IDENTITY_005",
  CAPABILITY_MISSING: "IDENTITY_006",
} as const;

export type OperationalIdentityErrorCode =
  (typeof OPERATIONAL_IDENTITY_ERROR)[keyof typeof OPERATIONAL_IDENTITY_ERROR];

const LEGACY_CODE_MAP: Record<string, OperationalIdentityErrorCode> = {
  ENTERPRISE_IDENTITY_CREDENTIAL_REVOKED: OPERATIONAL_IDENTITY_ERROR.CREDENTIAL_MISSING,
  ENTERPRISE_IDENTITY_CREDENTIAL_NOT_FOUND: OPERATIONAL_IDENTITY_ERROR.CREDENTIAL_MISSING,
  ENTERPRISE_IDENTITY_CREDENTIAL_FIELD_REQUIRED: OPERATIONAL_IDENTITY_ERROR.CREDENTIAL_MISSING,
  ENTERPRISE_IDENTITY_CREDENTIAL_SECRET_REQUIRED: OPERATIONAL_IDENTITY_ERROR.CREDENTIAL_MISSING,
  ENTERPRISE_IDENTITY_ACTION_UNSUPPORTED: OPERATIONAL_IDENTITY_ERROR.PERMISSION_DENIED,
  ENTERPRISE_IDENTITY_ACTION_SYNC_ONLY: OPERATIONAL_IDENTITY_ERROR.PERMISSION_DENIED,
  ENTERPRISE_IDENTITY_CAPABILITY_NOT_DISCOVERED: OPERATIONAL_IDENTITY_ERROR.CAPABILITY_MISSING,
};

export function resolveOperationalIdentityErrorCode(
  legacyCode: string,
): OperationalIdentityErrorCode {
  return LEGACY_CODE_MAP[legacyCode] ?? OPERATIONAL_IDENTITY_ERROR.PROVIDER_UNAVAILABLE;
}

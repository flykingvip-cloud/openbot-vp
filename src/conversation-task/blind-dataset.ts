/**
 * ConversationTask Runtime — independent BLIND test set (P1 acceptance round 2).
 *
 * Purpose: a larger, independently authored corpus to validate the frozen P1
 * detector/qualifier without overfitting. Methodology (per expert feedback):
 *
 *   1. Gold labels are assigned from the SPEC semantics BELOW, authored before
 *      running the detector. We do not reverse-engineer gold from implementation
 *      output, and we do not tune rules to fit these labels; any rule change is a
 *      spec-alignment fix, documented separately.
 *   2. No `expectedDetectorMiss` flags here — the blind run measures RAW recall.
 *      Recall misses on colloquial / elided / cross-turn work are expected for a
 *      high-precision detector and are reported, not hidden.
 *
 * Labelling rubric (from execution-plan.md §3–§6, §12):
 *   - chat (l0): question / discussion / opinion / musing / deferral; no work ask.
 *   - short_action (l1): a one-shot action reliably completable in the current run
 *     (look up / compute / translate / organize / sync once).
 *   - reminder: nudge a HUMAN at a future time; no continuous agent execution.
 *   - scheduled_action: a fixed action at a time, one-shot OR recurring, with NO
 *     cross-run evaluation state (daily send / periodic fixed report). Future time
 *     or recurrence ALONE never makes it L2.
 *   - long_running_candidate (l2): cannot complete in the current run AND must
 *     continue from PERSISTENT EVALUATION state — monitoring, waiting for an
 *     external condition, anomaly/threshold, multi-cycle trend/acceptance.
 *   - needs_clarification: work intent detected but missing goal, or a revision to
 *     an existing task whose target P1 cannot resolve (bound in P3).
 *
 * Side-effect gold: `none` for in-conversation notify to the requester
 * (通知我/提醒我/汇报/发我); `outbound_message` for delivery to an external
 * channel (发到邮箱/发送给某人/推送一条); `external_write` for CRM/系统/数据库
 * writes; `broadcast` for 群发/全部/所有/大家/客户群. Side effect never changes the
 * work-type gold (CT7).
 */


function detachRule(rule: RuntimeRuleDeclaration): RuntimeRuleDeclaration {
  return {
    ...rule,
    enforcementPoints: [...rule.enforcementPoints],
    dependencies: {
      rules: [...rule.dependencies.rules],
      artifacts: [...rule.dependencies.artifacts],
    },
    tests: [...rule.tests],
  };
}

/** Detached data view for management consumers; no mutable runtime authority. */
export function listRuntimeRuleDeclarations(): RuntimeRuleDeclaration[] {
  return RULES.map(detachRule);
}

/** Lookup one detached declaration by id; undefined when unknown. */
export function getRuntimeRuleDeclaration(id: string): RuntimeRuleDeclaration | undefined {
  const found = RULES.find((rule) => rule.id === id);
  return found ? detachRule(found) : undefined;
}

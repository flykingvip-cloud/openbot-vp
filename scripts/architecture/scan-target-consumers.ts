import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const SRC_ROOT = path.join(REPO_ROOT, "src");
const BASELINE_DIR = path.join(
  REPO_ROOT,
  ".kiro/specs/gateway-plugins-monolith-decomposition/baseline",
);

type ImportKind = "facade" | "sibling-deep" | "external-package";

type ConsumerRow = {
  consumerFile: string;
  importStatement: string;
  importKind: ImportKind;
};

function basenameFromTarget(targetRel: string): string {
  return path.basename(targetRel, path.extname(targetRel));
}

function posixRel(abs: string): string {
  return path.relative(REPO_ROOT, abs).split(path.sep).join("/");
}

function resolveTargetPaths(targetRel: string): {
  facadeStem: string;
  subModuleDir: string;
} {
  const normalized = targetRel.replace(/\\/g, "/");
  const withoutExt = normalized.replace(/\.tsx?$/, "");
  const facadeStem = withoutExt;
  const subModuleDir = `${withoutExt}/`;
  return { facadeStem, subModuleDir };
}

function classifyImport(importPath: string, facadeStem: string, subModuleDir: string): ImportKind {
  const normalized = importPath.replace(/\\/g, "/");
  if (normalized.includes(subModuleDir) && normalized !== `${facadeStem}.js`) {
    return "sibling-deep";
  }
  if (
    normalized === `${facadeStem}.js` ||
    normalized === facadeStem ||
    normalized.endsWith(`/${path.basename(facadeStem)}.js`) ||
    normalized.endsWith(`/${path.basename(facadeStem)}`)
  ) {
    return "facade";
  }
  if (normalized.startsWith(".") && normalized.includes(facadeStem.split("/").pop() ?? "")) {
    return "facade";
  }
  if (!normalized.startsWith(".") && !normalized.startsWith("/")) {
    return "external-package";
  }
  if (normalized.includes(`${facadeStem}/`)) {
    return "sibling-deep";
  }
  return "facade";
}

function extractImportsFromLine(line: string): string[] {
  const matches: string[] = [];
  const staticRe = /from\s+["']([^"']+)["']/g;
  const dynamicRe = /import\s*\(\s*["']([^"']+)["']\s*\)/g;
  let m: RegExpExecArray | null;
  while ((m = staticRe.exec(line)) !== null) {
    matches.push(m[1]);
  }
  while ((m = dynamicRe.exec(line)) !== null) {
    matches.push(m[1]);
  }
  return matches;
}

function walkTsFiles(dir: string, out: string[]): void {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const abs = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === "node_modules" || entry.name === "dist") {
        continue;
      }
      walkTsFiles(abs, out);
      continue;
    }
    if (/\.tsx?$/.test(entry.name)) {
      out.push(abs);
    }
  }
}

function scanConsumers(targetRel: string): ConsumerRow[] {
  const { facadeStem, subModuleDir } = resolveTargetPaths(targetRel);
  const facadeBase = path.basename(facadeStem);
  const rows: ConsumerRow[] = [];
  const files: string[] = [];
  walkTsFiles(SRC_ROOT, files);

  for (const abs of files) {
    const consumerRel = posixRel(abs);
    if (consumerRel === targetRel) {
      continue;
    }
    const content = fs.readFileSync(abs, "utf8");
    const lines = content.split("\n");
    for (let i = 0; i < lines.length; i++) {
      const line = lines[i];
      if (!line.includes("import")) {
        continue;
      }
      const specifiers = extractImportsFromLine(line);
      for (const spec of specifiers) {
        const hitsTarget =
          spec === `${facadeStem}.js` ||
          spec === facadeStem ||
          spec.startsWith(subModuleDir) ||
          spec.includes(`/${facadeBase}/`) ||
          (spec.endsWith(`/${facadeBase}.js`) && spec.startsWith("."));
        if (!hitsTarget) {
          continue;
        }
        const importKind = classifyImport(spec, facadeStem, subModuleDir);
        const stmtLines: string[] = [line.trim()];
        if (line.includes("{") && !line.includes("}")) {
          for (let j = i + 1; j < Math.min(i + 12, lines.length); j++) {
            stmtLines.push(lines[j].trim());
            if (lines[j].includes("}")) {
              break;
            }
          }
        }
        rows.push({
          consumerFile: consumerRel,
          importStatement: stmtLines.join(" "),
          importKind,
        });
      }
    }
  }

  return rows.toSorted((a, b) => {
    const fileCmp = a.consumerFile.localeCompare(b.consumerFile);
    if (fileCmp !== 0) {
      return fileCmp;
    }
    return a.importStatement.localeCompare(b.importStatement);
  });
}

function renderMarkdown(targetRel: string, rows: ConsumerRow[]): string {
  const lines = [
    `# Target_Module Consumers — ${targetRel}`,
    "",
    "Generated by `scripts/architecture/scan-target-consumers.ts`. Do not edit by hand.",
    "",
    `Consumer count: ${rows.length}`,
    "",
    "Import Kind legend:",
    "",
    "- `facade` — relative import resolving to the Target_Module's facade path.",
    "- `sibling-deep` — import resolving under the future Sub_Module directory.",
    "- `external-package` — bare specifier resolving to the Target_Module via a workspace package alias.",
    "",
    "| Consumer File | Import Statement | Import Kind |",
    "| --- | --- | --- |",
  ];

  for (const row of rows) {
    const stmt = row.importStatement.replace(/\|/g, "\\|");
    lines.push(`| ${row.consumerFile} | ${stmt} | ${row.importKind} |`);
  }

  lines.push("");
  return lines.join("\n");
}

function main(): void {
  const targetArg = process.argv[2];
  if (!targetArg) {
    console.error("Usage: pnpm baseline:consumers <repo-relative-target.ts>");
    process.exit(1);
  }

  const targetRel = targetArg.replace(/\\/g, "/");
  const rows = scanConsumers(targetRel);
  const outPath = path.join(BASELINE_DIR, `${basenameFromTarget(targetRel)}-consumers.md`);
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, renderMarkdown(targetRel, rows), "utf8");
  console.log(`Wrote ${path.relative(REPO_ROOT, outPath)} (${rows.length} consumers)`);
}

const scriptPath = fileURLToPath(import.meta.url);
if (process.argv[1] && path.resolve(process.argv[1]) === scriptPath) {
  main();
}
